# shellcheck shell=bash
# Blue-green core for NEXUS (deploy/bluegreen/README.md). Sourced by deploy/dev/deploy-nexus-dev.sh and
# deploy/bluegreen/deploy-nexus-bluegreen.sh, which set:
#   PROFILE        dev | prod
#   SLOT_PREFIX    container name prefix: <prefix>blue / <prefix>green
#   WEB            nginx container (mounts $NGINX_DIR at conf.d and $WEBROOT at /usr/share/nginx/html)
#   NGINX_DIR      conf.d on the host (default.conf generated, 00-bluegreen.conf = the switch)
#   WEBROOT        html root on the host: blue/ green/ _archive/assets/
#   BG_STATE       state dir: live, epoch, history.log, shared/live (mounted read-only into the slots)
#   KEEP_MINUTES   how long the previous slot stays up for an instant rollback
#   RAW_PORT       host port of nginx's raw listener (always the live slot)
#   SELF           path of the calling deploy script (for the delayed `finish`)
# State is plain files; every change of slots happens under the short switch lock $BG_LOCK, never under the
# (long) deploy lock, so `rollback` is never stuck behind a build.

BG_LOCK="${BG_LOCK:-/tmp/nexus-${PROFILE}-bluegreen.lock}"
ARCHIVE_DAYS="${ARCHIVE_DAYS:-7}"

bg_other() { [ "$1" = blue ] && echo green || echo blue; }
# "legacy" = the single pre-blue-green container ($LEGACY_C), only during the first (bootstrap) release.
bg_c() { if [ "$1" = legacy ]; then echo "${LEGACY_C:?}"; else echo "${SLOT_PREFIX}$1"; fi; }
bg_live() { cat "$BG_STATE/live" 2>/dev/null || true; }
bg_epoch() { cat "$BG_STATE/epoch" 2>/dev/null || echo 0; }
bg_new_epoch() { local e; e="$(date +%s%N)-$1"; echo "$e" > "$BG_STATE/epoch.tmp" && mv -f "$BG_STATE/epoch.tmp" "$BG_STATE/epoch"; echo "$e"; }
bg_log() { printf '%s %s\n' "$(date '+%F %T')" "$*" >> "$BG_STATE/history.log"; }
bg_running() { [ "$(docker inspect -f '{{.State.Running}}' "$(bg_c "$1")" 2>/dev/null)" = "true" ]; }
bg_exists() { docker inspect "$(bg_c "$1")" >/dev/null 2>&1; }
bg_ms() { date +%s%3N; }

bg_init_state() {
  mkdir -p "$BG_STATE/shared" "$WEBROOT/_archive/assets" "$NGINX_DIR"
  chmod 755 "$BG_STATE/shared"
}

# /api/health from INSIDE the slot (independent of nginx). $2 = expected slot name (optional).
bg_health() {
  docker exec "$(bg_c "$1")" node -e '
    fetch("http://127.0.0.1:3000/api/health").then(async r => {
      const j = await r.json().catch(() => ({}))
      process.exit(r.status === 200 && (!process.argv[1] || j.slot === process.argv[1]) ? 0 : 1)
    }).catch(() => process.exit(1))' "${2:-}" 2>/dev/null
}

bg_health_json() {  # one line of JSON (or "down")
  docker exec "$(bg_c "$1")" node -e 'fetch("http://127.0.0.1:3000/api/health").then(r=>r.text()).then(t=>console.log(t)).catch(()=>console.log("down"))' 2>/dev/null || echo down
}

bg_wait_healthy() {  # slot tries(2 s each)
  local i
  for i in $(seq 1 "${2:-45}"); do bg_health "$1" "$1" && { echo "   $(bg_c "$1") healthy after $i tries"; return 0; }; sleep 2; done
  return 1
}

# Write conf.d/00-bluegreen.conf: live and preview upstreams + html roots. nginx resolves upstream host names
# at (re)load, so the preview may only name a RUNNING container; otherwise it points at the live slot too.
bg_write_upstreams_file_only() {  # live preview -> $NGINX_DIR/00-bluegreen.conf.new
  local live="$1" prev="$2" f="$NGINX_DIR/00-bluegreen.conf"
  bg_running "$prev" || prev="$live"
  cat > "$f.new" <<NGX
# GENERATED by bg-lib.sh at every switch — do not edit. live=$live preview=$prev
# max_fails=0: one refused connection must never mark the only server down for 10 s (that is a 502 burst).
upstream nexus_app_live    { server $(bg_c "$live"):3000 max_fails=0; }
upstream nexus_app_preview { server $(bg_c "$prev"):3000 max_fails=0; }
map \$host \$nexus_live_root    { default /usr/share/nginx/html/$live; }
map \$host \$nexus_preview_root { default /usr/share/nginx/html/$prev; }
NGX
  [ -f "$f" ] && cp -f "$f" "$f.bak"
  mv -f "$f.new" "$f"
}

bg_write_upstreams() {  # live preview   (file + nginx -t; the old file comes back if the test fails)
  local live="$1" prev="$2" f="$NGINX_DIR/00-bluegreen.conf"
  bg_running "$prev" || prev="$live"
  bg_write_upstreams_file_only "$live" "$prev"
  if ! docker exec "$WEB" nginx -t >/dev/null 2>&1; then
    red "   nginx -t failed with live=$live preview=$prev:"; docker exec "$WEB" nginx -t 2>&1 | tail -3
    [ -f "$f.bak" ] && mv -f "$f.bak" "$f"
    return 1
  fi
  return 0
}

bg_reload() { docker exec "$WEB" nginx -s reload >/dev/null 2>&1; }

# Wait until nginx's raw listener answers from slot $1 (new workers up).
bg_wait_served_by() {
  local i s
  for i in $(seq 1 100); do
    s=$(curl -s -m 2 "http://127.0.0.1:$RAW_PORT/api/health" | sed -n 's/.*"slot":"\([a-z]*\)".*/\1/p')
    [ "$s" = "$1" ] && return 0
    sleep 0.05
  done
  return 1
}

# The switch itself. Caller holds $BG_LOCK and has verified $new healthy.
bg_switch() {  # new [reason] [old]
  local new="$1" old="${3:-$(bg_other "$1")}"
  local t0; t0=$(bg_ms)
  bg_write_upstreams "$new" "$old" || return 1
  printf '%s\n' "$new" > "$BG_STATE/shared/live.tmp" && mv -f "$BG_STATE/shared/live.tmp" "$BG_STATE/shared/live"
  printf '%s\n' "$new" > "$BG_STATE/live.tmp" && mv -f "$BG_STATE/live.tmp" "$BG_STATE/live"
  bg_reload || { red "   nginx reload failed"; return 1; }
  if ! bg_wait_served_by "$new"; then red "   nginx does not answer from $new after the reload"; return 1; fi
  local t1; t1=$(bg_ms)
  # Demote the old slot: it re-reads the live file (lets go of the singleton lock) and closes its realtime
  # connections so clients reconnect — through nginx, to $new.
  # Only to a build that handles it (its /api/health reports "leader"): for an older build SIGUSR2 has
  # no handler and would simply kill the process mid-drain.
  if bg_running "$old" && bg_health_json "$old" | grep -q '"leader":'; then
    docker kill -s USR2 "$(bg_c "$old")" >/dev/null 2>&1
  fi
  BG_EPOCH=$(bg_new_epoch "switch-$new")
  bg_log "switch -> $new (${2:-deploy}) in $((t1 - t0)) ms, epoch $BG_EPOCH"
  echo "   switched to $new in $((t1 - t0)) ms (nginx graceful reload; in-flight requests finish on $old)"
}

# Stop the previous slot after KEEP_MINUTES unless something changed meanwhile (epoch).
bg_schedule_finish() {  # epoch slot
  [ "${KEEP_MINUTES:-0}" -gt 0 ] || { "$SELF" finish "$1" "$2"; return; }
  setsid nohup bash -c "sleep $((KEEP_MINUTES * 60)); exec '$SELF' finish '$1' '$2'" >> "$BG_STATE/finish.log" 2>&1 < /dev/null &
  echo "$(date -d "+$KEEP_MINUTES min" '+%F %T') $2 $1" > "$BG_STATE/finish-at"
  echo "   $(bg_c "$2") stays up $KEEP_MINUTES min for an instant rollback: $SELF rollback"
}

bg_finish() {  # epoch slot   (caller holds $BG_LOCK)
  local epoch="$1" slot="$2"
  if [ "$(bg_epoch)" != "$epoch" ]; then echo "$(date '+%F %T') finish $slot skipped: epoch changed"; return 0; fi
  if [ "$(bg_live)" = "$slot" ]; then echo "$(date '+%F %T') finish $slot skipped: it is live"; return 0; fi
  if bg_running "$slot"; then
    docker stop -t 30 "$(bg_c "$slot")" >/dev/null 2>&1
    bg_write_upstreams "$(bg_live)" "$(bg_live)" && bg_reload
    bg_log "finish: stopped $slot (epoch $epoch)"
    echo "$(date '+%F %T') finish: stopped $(bg_c "$slot")"
  fi
  rm -f "$BG_STATE/finish-at"
}

# Instant rollback: flip nginx back to the other slot if it is still running and healthy. If it was
# already stopped, start it first (cold rollback, ~15-30 s, still no downtime: nginx stays put until it is healthy).
bg_rollback() {
  local live; live="$(bg_live)"
  [ -n "$live" ] || { red "no blue-green state yet — nothing to roll back to"; return 1; }
  local target; target="$(bg_other "$live")"
  bg_exists "$target" || { red "$(bg_c "$target") does not exist — nothing to roll back to"; return 1; }
  if ! bg_running "$target"; then
    echo "   $(bg_c "$target") is stopped — starting it (cold rollback)"
    docker start "$(bg_c "$target")" >/dev/null || return 1
    bg_wait_healthy "$target" 30 || { red "   $(bg_c "$target") not healthy — staying on $live"; return 1; }
  fi
  bg_health "$target" "$target" || { red "   $(bg_c "$target") unhealthy — staying on $live"; return 1; }
  local t0; t0=$(bg_ms)
  bg_switch "$target" rollback || return 1
  echo "   rollback total $(( $(bg_ms) - t0 )) ms (live: $target, commit $(docker inspect -f '{{index .Config.Labels "nexus.bluegreen.commit"}}' "$(bg_c "$target")" 2>/dev/null))"
  bg_schedule_finish "$BG_EPOCH" "$live"
}

# SPA: install a build as slot $1's html (atomic directory swap); its hashed assets also go to the archive.
bg_spa_install() {  # slot builddir
  local slot="${1:?slot}" b="${2:?builddir}" root="${WEBROOT:?WEBROOT unset}"
  rsync -a --delete "$b/" "$root/$slot.tmp/" || return 1
  [ -d "$root/$slot" ] && mv "$root/$slot" "$root/$slot.old"
  mv "$root/$slot.tmp" "$root/$slot" || return 1
  [ -d "$root/$slot.old" ] && rm -r "${root:?}/${slot:?}.old"
  [ -d "$b/assets" ] && rsync -a "$b/assets/" "$root/_archive/assets/"
  chmod -R a+rX "$root/$slot" "$root/_archive"
}

bg_archive_prune() {  # drop archived assets older than ARCHIVE_DAYS that neither slot uses
  local n=0 f base
  while IFS= read -r -d '' f; do
    base="${f#"$WEBROOT"/_archive/}"
    { [ -e "$WEBROOT/blue/$base" ] || [ -e "$WEBROOT/green/$base" ]; } && continue
    rm -f "$f" && n=$((n + 1))
  done < <(find "$WEBROOT/_archive/assets" -type f -mtime +"$ARCHIVE_DAYS" -print0 2>/dev/null)
  echo "   asset archive: $(find "$WEBROOT/_archive/assets" -type f | wc -l) files kept, $n pruned (>${ARCHIVE_DAYS} d, unused)"
}

bg_status() {
  local live; live="$(bg_live)"
  echo "live slot: ${live:-<none>}   epoch: $(bg_epoch)"
  [ -f "$BG_STATE/finish-at" ] && echo "previous slot stops at: $(cut -d' ' -f1-3 "$BG_STATE/finish-at")"
  local s
  for s in blue green; do
    if bg_exists "$s"; then
      printf '  %-6s %-24s %-8s image=%s commit=%s released=%s\n' "$s" "$(bg_c "$s")" \
        "$(bg_running "$s" && echo running || echo stopped)" \
        "$(docker inspect -f '{{.Config.Image}}' "$(bg_c "$s")")" \
        "$(docker inspect -f '{{index .Config.Labels "nexus.bluegreen.commit"}}' "$(bg_c "$s")")" \
        "$(docker inspect -f '{{index .Config.Labels "nexus.bluegreen.released"}}' "$(bg_c "$s")")"
      bg_running "$s" && echo "         health: $(bg_health_json "$s" | head -c 220)"
    else
      printf '  %-6s %-24s absent\n' "$s" "$(bg_c "$s")"
    fi
  done
  echo "nginx 00-bluegreen.conf: $(head -1 "$NGINX_DIR/00-bluegreen.conf" 2>/dev/null | sed 's/.*live=/live=/')"
  echo "last switches:"; tail -5 "$BG_STATE/history.log" 2>/dev/null | sed 's/^/  /'
}
